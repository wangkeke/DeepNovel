def platform_writing_skin_for_planning(platform_key: str, max_chars: int = 2200) -> str:
    """长篇策划：与开篇同源的 PLATFORM_STYLES 节奏/句式皮囊（可截断以控 token）。"""
    if max_chars <= 0:
        return ""
    key = (platform_key or "").strip() or "通用网文"
    style = PLATFORM_STYLES.get(key)
    if style is None:
        style = PLATFORM_STYLES.get("通用网文", "")
    style = (style or "").strip()
    if not style:
        return ""
    if len(style) > max_chars:
        return style[:max_chars] + "\n…（平台节奏指南截断）\n"
    return style


def platform_planning_bundle(state: dict, *, skin_max_chars: int = 2200) -> str:
    """班底 / 分卷 / 事件链：宏读者定位 + 可选节奏皮囊。fill_details 等可传 skin_max_chars=0 仅保留宏。"""
    macro = platform_macro_user_block(state)
    skin = platform_writing_skin_for_planning(
        str(state.get("platform_style") or ""),
        max_chars=skin_max_chars,
    )
