# prompts.common.feedback_handling

USER_FEEDBACK_HANDLING = """
## 处理用户修改意见

用户意见：
{user_feedback}

在开始生成之前，先完成以下两步分析：

【第一步：提取确定性信息（必须在输出中保留）】

必须保留的内容：
  • 具体经历（如：盗墓出身、坐牢20年、父母离世、兄弟散亡）
  • 明确的人物关系（如：兄弟、父母、哥哥姐姐）
  • 核心动机（如：带兄弟走正道、弥补遗憾、为某人复仇）
  • 情感基调（如：忏悔、救赎、愤怒、执念）
  • 明确的时间跨度或关键事件节点

可以由模型自由处理的内容：
  • 人物名字
    用户意见里出现的名字往往是占位符（如"张三""李四"）
    模型应根据题材和风格重新命名，不照搬用户的占位符
    例外：如果用户在之前的交互中已确认了某个名字，则保留
  • 具体场景细节（用户给方向，模型负责细节）
  • 对话内容（用户描述的逻辑，模型转化成具体对话）

【第二步：理解方向性信息（需要创作转化）】

用户意见里可能包含逻辑思路或情节方向，例如：
  "主角被人陷害，在关键时刻反败为胜"
  → 这是逻辑方向，不是具体情节
  → 保留"被陷害→反败为胜"的逻辑
  → 由模型设计具体的陷害方式、反转手段、场景
  → 但必须先确认：陷害成立的前提是主角此时有被针对的价值或威胁
    若主角当前无价值无威胁，需要先设计"主角为什么值得被陷害"的前因

【禁止事项】
  ✗ 用题材通用模板替换用户的具体描述
  ✗ 忽略用户明确提到的任何经历、关系或动机
  ✗ 把用户的具体故事"升华"成另一个套路
  ✗ 照搬用户意见中的占位符名字作为正式角色名
"""
