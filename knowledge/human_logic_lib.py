def format_character_logics(char_cards: list[dict]) -> str:
    """将人物卡中的 dominant_logics 格式化为可注入 expand1 的文本。"""
    result: list[str] = []
    for card in char_cards:
        name = card.get("name", "")
        for logic_name in card.get("dominant_logics", []):
            logic = HUMAN_LOGIC_LIB.get(logic_name, {})
            if logic:
                steps = "\n".join(f"    {step}" for step in logic.get("execution_steps", []))
                result.append(
                    f"{name} — {logic_name}\n"
                    f"  核心：{logic.get('core_essence', '')}\n"
                    f"  执行程序：\n{steps}"
                )
    return "\n\n".join(result) if result else "无记录"


def get_logic_names_and_essences() -> str:
    """返回所有人性逻辑的名称和核心本质，供推导 prompt 使用。"""
    lines = [f"  - {name}：{logic.get('core_essence', '')[:50]}…" for name, logic in HUMAN_LOGIC_LIB.items()]
    return "\n".join(lines)
