"""
冰山反推：三阶段共用的「开篇锚点 + 格局链」约束，减少改名、换事、套通用模板。
"""
from __future__ import annotations


def format_iceberg_anchor_block(opening_text: str) -> str:
    """
    嵌入三条用户消息（世界 / 班底 / 宏观），与开篇原文对齐，不要求本地 NER 完美提取人名。
    """
    ot = (opening_text or "").strip()
    if not ot:
        return "【锚点约束】开篇正文为空，请勿推演。"

    return (
        "【锚点约束（最高优先级·阶段1世界／阶段1班底／阶段2宏观 共用）】\n"
        "以下【开篇原文】是事实唯一来源。所有输出必须与之一致，禁止各专家各自脑补成另一套故事。\n\n"
        "禁止：\n"
        "· 给主角改名、换姓、另起标准名（例如正文为「沈微」却写成「姜雪」）。\n"
        "· 换掉开篇已出场的核心对立者或施害者，改写成无关小人物支线。\n"
        "· 把开篇核心事件偷换成题材常见套路（如开篇为妃嫔级设局构陷，却写成宫女争炭、反杀内务府太监等与原文无关情节）。\n\n"
        "强制：\n"
        "1. 主角：全名、他人称呼、职衔所指的须为同一人，与原文一致。\n"
        "2. 人物与冲突：仅延展原文已出场或可由当场情景直接推出的人物；不得用模板人物顶替。\n"
        "3. 世界与权力结构：只补充原文**已暗示**的规则与层级，少即是多；禁止为填字段编造与原文无关的庞大设定。\n"
        "4. 阶段2 宏观：volume_1_goal、core_conflict、escalation_path 必须从开篇**具体事件**出发，按链追问："
        "谁推动 → 为何此时发生 → 背后更大矛盾；逐级放大到全书。禁止跳过开篇事件直接套「底层逆袭」等通用大纲。\n\n"
        "【格局链·正例】高位者设局陷害主角 → 其处境与动机 → 与其结盟或制衡的更高权力。\n"
        "【格局链·反例】无视开篇陷害，另写与原文无关的资源纠纷或另一条人生。\n\n"
        "【开篇原文】\n---\n"
        f"{ot}\n"
        "---\n"
    )
